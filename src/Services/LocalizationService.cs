    public static class LocalizationService
    {
        [DllImport("kernel32.dll")]
        private static extern ushort GetUserDefaultUILanguage();

        private static string _currentLang = "zh-CN";
        private static readonly Dictionary<string, Dictionary<string, string>> _tables = BuildTables();

        public static string CurrentLanguage { get { return _currentLang; } }

        public static void SetLanguage(string languageCode)
        {
            if (string.IsNullOrEmpty(languageCode) || languageCode.Equals("auto", StringComparison.OrdinalIgnoreCase))
            {
                _currentLang = DetectSystemLanguage();
            }
            else if (_tables.ContainsKey(languageCode))
            {
                _currentLang = languageCode;
            }
            else
            {
                _currentLang = "en-US";
            }
        }

        public static string DetectSystemLanguage()
        {
            string name = CultureInfo.CurrentUICulture.Name;
            try
            {
                ushort langId = GetUserDefaultUILanguage();
                if (langId != 0)
                {
                    name = new CultureInfo(langId).Name;
                }
            }
            catch
            {
            }

            if (name.StartsWith("zh-TW", StringComparison.OrdinalIgnoreCase) ||
                name.StartsWith("zh-HK", StringComparison.OrdinalIgnoreCase) ||
                name.StartsWith("zh-MO", StringComparison.OrdinalIgnoreCase) ||
                name.StartsWith("zh-Hant", StringComparison.OrdinalIgnoreCase))
            {
                return "zh-TW";
            }
            if (name.StartsWith("zh", StringComparison.OrdinalIgnoreCase)) return "zh-CN";
            if (name.StartsWith("ja", StringComparison.OrdinalIgnoreCase)) return "ja-JP";
            if (name.StartsWith("ko", StringComparison.OrdinalIgnoreCase)) return "ko-KR";
            return "en-US";
        }

        public static string T(string key)
        {
            Dictionary<string, string> table;
            if (_tables.TryGetValue(_currentLang, out table))
            {
                string val;
                if (table.TryGetValue(key, out val)) return val;
            }
            Dictionary<string, string> fallback;
            if (_tables.TryGetValue("en-US", out fallback))
            {
                string val;
                if (fallback.TryGetValue(key, out val)) return val;
            }
            return key;
        }

        public static string F(string key, params object[] args)
        {
            return string.Format(T(key), args);
        }

